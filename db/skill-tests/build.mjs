// Verifies a skill-test question bank and writes its migration. Every question
// with a run()/check() is executed in Node and must agree with its marked answer;
// the build fails on any mismatch or structural problem.
// Usage: node db/skill-tests/build.mjs <bank.mjs> <out.sql>
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const [bankPath, outPath] = process.argv.slice(2);
const { stack, retireSlug, levels } = await import(pathToFileURL(resolve(bankPath)).href);
const migrationName = basename(outPath, ".sql");

const TARGETS = {
  beginner_1: 5, beginner_2: 5, beginner_3: 6, intermediate_1: 6, intermediate_2: 7,
  intermediate_3: 7, advanced_1: 8, advanced_2: 8, advanced_3: 9,
};
const problems = [];
const seenQuestions = new Set();

function seededRandom(seed) {
  let h = createHash("sha256").update(seed).digest();
  let i = 0;
  return () => {
    if (i + 4 > h.length) { h = createHash("sha256").update(h).digest(); i = 0; }
    const v = h.readUInt32BE(i); i += 4;
    return v / 2 ** 32;
  };
}
function stableUuid(name) {
  const b = createHash("sha1").update(`ipskill-skill-test:${name}`).digest();
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // RFC 4122 variant
  const h = b.subarray(0, 16).toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
const sql = (s) => `'${s.replace(/'/g, "''")}'`;

let verified = 0;
let conceptual = 0;
const rows = [];
const positionTally = [0, 0, 0, 0];

for (const level of levels) {
  const levelKey = level.slug.replace(/^.*-(beginner|intermediate|advanced)-(\d)$/, "$1_$2");
  const target = TARGETS[levelKey];
  if (!target) problems.push(`${level.slug}: unknown level`);
  if (level.questions.length < target * 2) {
    problems.push(`${level.slug}: ${level.questions.length} questions, want >= ${target * 2} (2x target ${target})`);
  }

  // Balanced, seeded placement of the correct answer.
  const positions = level.questions.map((_, i) => i % 4);
  const rand = seededRandom(level.slug);
  for (let i = positions.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [positions[i], positions[j]] = [positions[j], positions[i]];
  }

  for (const [idx, item] of level.questions.entries()) {
    const label = `${level.slug} #${idx + 1}`;
    if (!item.q || !Array.isArray(item.c) || item.c.length !== 4) problems.push(`${label}: needs a question and exactly 4 choices`);
    if (new Set(item.c).size !== item.c.length) problems.push(`${label}: duplicate choices`);
    if (item.c.some((ch) => !ch || !ch.trim())) problems.push(`${label}: empty choice`);
    if (/\n/.test(item.q) || item.c.some((ch) => /\n/.test(ch))) problems.push(`${label}: newline (renders as one line)`);
    const key = item.q.trim().toLowerCase();
    if (seenQuestions.has(key)) problems.push(`${label}: duplicate question text`);
    seenQuestions.add(key);

    if (item.run) {
      const got = await item.run();
      if (got !== item.c[0]) problems.push(`${label}: run() gave ${JSON.stringify(got)}, answer is ${JSON.stringify(item.c[0])}`);
      else verified++;
    } else if (item.check) {
      const ok = await item.check();
      if (ok !== true) problems.push(`${label}: check() failed for answer ${JSON.stringify(item.c[0])}`);
      else verified++;
    } else {
      conceptual++;
    }

    const correctIndex = positions[idx];
    positionTally[correctIndex]++;
    const distractors = item.c.slice(1);
    const choices = [...distractors.slice(0, correctIndex), item.c[0], ...distractors.slice(correctIndex)];
    rows.push({
      id: stableUuid(`${level.slug}:${idx + 1}`),
      templateId: level.templateId,
      text: item.q,
      choices,
      correctIndex,
      order: idx + 1,
    });
  }
}

const total = rows.length;
console.log(`questions: ${total} | verified by running: ${verified} | conceptual: ${conceptual}`);
console.log(`correct-answer positions A/B/C/D: ${positionTally.join(" / ")}`);
for (const l of levels) console.log(`  ${l.slug}: ${l.questions.length}`);
if (problems.length) {
  console.error(`\n${problems.length} problem(s):\n- ${problems.join("\n- ")}`);
  process.exit(1);
}

const out = [];
out.push(`-- ${migrationName}`);
out.push("--");
out.push(`-- Real question banks for the 9 leveled ${stack} skill tests (Beginner 1 to`);
out.push("-- Advanced 3), which 0012 seeded as inactive, content-empty placeholders. Each");
out.push("-- bank holds about twice its target_question_count, so the /start route serves a");
out.push("-- different random subset on a retake. Generated by db/skill-tests/build.mjs,");
out.push("-- which ran every computable answer in Node and spread correct answers evenly");
out.push("-- across the four positions.");
out.push("--");
out.push(`-- Also retires '${retireSlug}', per the plan in improvements.md (the`);
out.push("-- single-tier tests stay active only until their leveled equivalents exist).");
out.push("-- is_active only hides it from the test list; past attempts and verified");
out.push("-- badges keep working. Idempotent: fixed question ids + on conflict do nothing.");
out.push("");
out.push("insert into skill_test_questions");
out.push("  (id, template_id, question_text, choices, correct_index, points, order_index)");
out.push("values");
out.push(
  rows
    .map(
      (r) =>
        `  (${sql(r.id)}, ${sql(r.templateId)}, ${sql(r.text)}, ARRAY[${r.choices.map(sql).join(", ")}], ${r.correctIndex}, 1, ${r.order})`
    )
    .join(",\n")
);
out.push("on conflict (id) do nothing;");
out.push("");
for (const level of levels) {
  out.push(
    `update skill_test_templates set description = ${sql(level.description)}, is_active = true where id = ${sql(level.templateId)};`
  );
}
out.push("");
out.push(`update skill_test_templates set is_active = false where slug = ${sql(retireSlug)};`);
out.push("");
writeFileSync(outPath, out.join("\n"));
console.log(`\nwrote ${outPath}`);
